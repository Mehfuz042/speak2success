_RECENT = {}  # (category, difficulty) -> deque of recently used questions


def _shuffled_pool(pool, key):
    """Shuffle a pool, de-prioritizing questions used in recent interviews so the
    same question is not asked back-to-back (best-effort, per process)."""
    recent = _RECENT.setdefault(key, deque(maxlen=max(8, len(pool))))
    if len(recent) < len(pool):
        fresh = [q for q in pool if q not in recent]
        if fresh:
            pool = fresh
    random.shuffle(pool)
    return pool


def _mark_used(pool, key, questions):
    _RECENT.setdefault(key, deque(maxlen=max(8, len(pool)))).extend(questions)


def _offline_generate(role, skills, difficulty, category, count):
    effective = category if category in OFFLINE_BANK else "Technical"
    bank = OFFLINE_BANK[effective]
    pool = _shuffled_pool(bank.get(difficulty, bank["Easy"])[:], (effective, difficulty))

    role_questions = []
    # 1. Use the curated 20-question bank for this role (available for ALL rounds)
    iq = ROLE_INTERVIEW_QUESTIONS.get(role, [])
    if iq:
        role_questions = iq[:]

    # 2. Fallback to round-specific role questions if no curated bank
    if not role_questions:
        if effective == "Technical":
            topics = ROLE_TECHNICAL_TOPICS.get(role, [])
            if not topics and skills:
                topics = skills[:4]
            role_questions = [
                f"Walk me through your understanding of {t} and how you've applied it."
                for t in topics
            ]
            if skills:
                role_questions.append(
                    f"You listed {', '.join(skills[:3])} on your resume — describe a project "
                    f"where you used one of these to solve a real problem."
                )
        elif effective == "Managerial":
            role_questions = ROLE_MANAGERIAL_QUESTIONS.get(role, [])[:]
        elif effective == "HR":
            role_questions = ROLE_HR_QUESTIONS.get(role, [])[:]

    # Prioritize role-specific questions first, then fill remaining slots from the generic bank.
    recency_key = (effective, difficulty)
    if role_questions:
        shuffled_role = _shuffled_pool(role_questions, recency_key)
        questions = shuffled_role[:count]
        remaining = count - len(questions)
        if remaining > 0:
            generic_pool = _shuffled_pool(pool[:], recency_key)
            questions.extend(generic_pool[:remaining])
    else:
        questions = _shuffled_pool(pool, recency_key)[:count]

    _mark_used(questions, recency_key, questions)

    return [{"question": q, "category": effective, "difficulty": difficulty} for q in questions]


def _ai_generate(role, skills, experience_years, difficulty, category, count):
    client = get_client()
    prompt = f"""
You are an expert interviewer for the "{category}" round of a professional interview.
The candidate is applying for a "{role}" role.
Candidate skills: {', '.join(skills) if skills else 'general software development'}.
Candidate experience: ~{experience_years} years.

Generate {count} {difficulty.lower()} difficulty {category} interview questions.
Return ONLY a JSON array, no prose, no markdown fences, in this exact format:
[{{"question": "...", "category": "{category}", "difficulty": "{difficulty}"}}, ...]
"""
    response = client.chat.completions.create(
        model=model_name(),
        messages=[{"role": "user", "content": prompt}],
        temperature=0.8,
    )
    raw = response.choices[0].message.content.strip()
    raw = raw.replace("```json", "").replace("```", "").strip()
    return json.loads(raw)


def generate_questions(role="Software Engineer", skills=None, experience_years=0,
                       difficulty="Medium", category="Technical", count=5):
    """Generate questions for one round/category; falls back to the offline bank."""
    skills = skills or []
    if is_configured():
        try:
            return _ai_generate(role, skills, experience_years, difficulty, category, count), "gemini"
        except Exception:  # noqa: S110 - silently fall back to the offline bank.
            pass
    return _offline_generate(role, skills, difficulty, category, count), "offline"


def generate_language_theory(language="python", difficulty="Medium", count=2):
    """Language-specific theory questions for the Technical round."""
    language = _normalize_language(language)
    pool = _shuffled_pool(
        list(LANGUAGE_TECHNICAL_TOPICS.get(language, LANGUAGE_TECHNICAL_TOPICS["python"])),
        ("language", language),
    )
    questions = pool[:count]
    _mark_used(pool, ("language", language), questions)
    return [
        {"question": q, "category": "Technical", "difficulty": difficulty, "language": language}
        for q in questions
    ]


def _normalize_language(language):
    aliases = {"py": "python", "js": "javascript", "node": "javascript", "c++": "cpp", "c": "cpp"}
    lang = (language or "python").strip().lower()
    return aliases.get(lang, lang)
